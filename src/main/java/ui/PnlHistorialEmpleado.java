    private void configurarHistorial() {
        Calendar calendario = Calendar.getInstance();
        calendario.set(Calendar.DAY_OF_MONTH, 1);

        java.util.Date inicioMes = calendario.getTime();
        java.util.Date hoy = new java.util.Date();

        dcDesde.setDateFormatString("dd/MM/yyyy");
        dcDesde.setDate(inicioMes);

        dcHasta.setDateFormatString("dd/MM/yyyy");
        dcHasta.setDate(hoy);

        txtBuscarHistorial.setText("");
        txtBuscarHistorial.setToolTipText(
                "Busca por fecha, referencia, producto, cliente o usuario"
        );

        cmbTipoHistorial.setModel(new javax.swing.DefaultComboBoxModel<>(
                new String[]{
                    "TODOS",
                    "HISTORIAL DE VENTAS",
                    "HISTORIAL PRODUCTOS"
                }
        ));

        tblHistorial.setModel(new DefaultTableModel(
                new Object[]{
                    "Fecha y hora",
                    "Tipo de movimiento",
                    "Referencia",
                    "Producto / cliente",
                    "Cantidad / total",
                    "Usuario responsable"
                },
                0
        ) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        });

        cmbTipoHistorial.addActionListener(e -> cargarHistorial());

        // Enter en el buscador aplica la búsqueda.
        txtBuscarHistorial.addActionListener(e -> cargarHistorial());

        // Al cambiar cualquiera de las fechas, vuelve a cargar la tabla.
        dcDesde.addPropertyChangeListener("date", e -> cargarHistorial());
        dcHasta.addPropertyChangeListener("date", e -> cargarHistorial());

        cargarHistorial();
    }

    private LocalDate convertirFecha(
            com.toedter.calendar.JDateChooser selector) {

        java.util.Date fecha = selector.getDate();

        if (fecha == null) {
            return null;
        }

        return fecha.toInstant()
                .atZone(ZoneId.systemDefault())
                .toLocalDate();
    }

    private void cargarHistorial() {
        LocalDate desde = convertirFecha(dcDesde);
        LocalDate hasta = convertirFecha(dcHasta);

        if (desde == null || hasta == null) {
            return;
        }

        if (desde.isAfter(hasta)) {
            JOptionPane.showMessageDialog(
                    this,
                    "La fecha Desde no puede ser posterior a Hasta.",
                    "Rango de fechas incorrecto",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String tipo = String.valueOf(cmbTipoHistorial.getSelectedItem());
        String busqueda = txtBuscarHistorial.getText();

        try {
            ReporteDAO dao = new ReporteDAO();

            java.util.List<Object[]> filas = dao.historialGeneral(
                    desde,
                    hasta,
                    tipo,
                    busqueda
            );

            DefaultTableModel modelo
                    = (DefaultTableModel) tblHistorial.getModel();

            modelo.setRowCount(0);

            for (Object[] fila : filas) {
                modelo.addRow(fila);
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo cargar el historial: " + ex.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

