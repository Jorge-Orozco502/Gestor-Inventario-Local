    private void btnDescargarPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDescargarPDFActionPerformed
        // TODO add your handling code here:
        if (tblHistorial.getRowCount() == 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "No hay registros en la tabla para exportar.",
                    "Historial vacío",
                    JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        JFileChooser selector = new JFileChooser();
        selector.setDialogTitle("Guardar historial en PDF");
        selector.setSelectedFile(new File("Historial.pdf"));
        selector.setFileFilter(
                new FileNameExtensionFilter("Archivo PDF (*.pdf)", "pdf")
        );

        if (selector.showSaveDialog(this)
                != JFileChooser.APPROVE_OPTION) {
            return;
        }

        File archivo = selector.getSelectedFile();

        if (!archivo.getName().toLowerCase().endsWith(".pdf")) {
            archivo = new File(
                    archivo.getParentFile(),
                    archivo.getName() + ".pdf"
            );
        }

        if (archivo.exists()) {
            int respuesta = JOptionPane.showConfirmDialog(
                    this,
                    "El archivo ya existe. ¿Deseas reemplazarlo?",
                    "Confirmar reemplazo",
                    JOptionPane.YES_NO_OPTION
            );

            if (respuesta != JOptionPane.YES_OPTION) {
                return;
            }
        }

        LocalDate desde = convertirFecha(dcDesde);
        LocalDate hasta = convertirFecha(dcHasta);

        String resumen = "Tipo: "
                + cmbTipoHistorial.getSelectedItem()
                + " | Período: "
                + desde
                + " a "
                + hasta
                + " | Búsqueda: "
                + txtBuscarHistorial.getText().trim()
                + " | Registros: "
                + tblHistorial.getRowCount();

        try {
            ExportadorReportes.exportarPdfHistorial(
                    archivo.getAbsolutePath(),
                    "Historial",
                    resumen,
                    tblHistorial
            );

            JOptionPane.showMessageDialog(
                    this,
                    "El PDF se guardó correctamente en:\n"
                    + archivo.getAbsolutePath(),
                    "PDF generado",
                    JOptionPane.INFORMATION_MESSAGE
            );

        } catch (IOException | DocumentException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo generar el PDF: " + ex.getMessage(),
                    "Error al exportar",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_btnDescargarPDFActionPerformed


